/**
 * Writes the generated part of `docs/parity-matrix.md` (between the
 * `matrix:begin` and `matrix:end` markers) from `results.json` and the
 * reviewed classifications in `review.ts`: the scores, the per-area table, the
 * ranked gap list, the surface table and every surface's driven interactions
 * with their literal results.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { APP_DIR } from '../../build'
import { REVIEWS, type Review } from './review'
import { SURFACES } from './surfaces'
import type { AreaId, ClientRun, Surface, SurfaceResult } from './types'
import { AREA_WEIGHTS, STATUS_SCORE, type Status } from './weights'

export const DOC = path.join(APP_DIR, 'docs/parity-matrix.md')
const BEGIN =
  '<!-- matrix:begin (generated by `bun run parity:matrix`; edit tools/matrix/review.ts, not this block) -->'
const END = '<!-- matrix:end -->'
const STATUSES: Status[] = ['ported', 'partial', 'broken', 'blocked', 'unverified', 'pending-unit']

interface Row {
  surface: Surface
  result?: SurfaceResult
  review?: Review
  previous?: PreviousRow
  status: Status
}

/**
 * A surface's columns and interaction lines as the page last recorded them.
 * `results.json` is not committed, so a partial run in a fresh checkout keeps
 * these for every surface it did not run instead of blanking them.
 */
interface PreviousRow {
  status: Status
  /** Auto, Web, GPUIX, full and region mismatch cells, as written. */
  cells: string[]
  interactions: string
}

function finalStatus(result?: SurfaceResult, review?: Review, previous?: PreviousRow): Status {
  if (review) return review.status
  return result ? result.auto : (previous?.status ?? 'unverified')
}

/** The surface rows and interaction entries of the page's generated block, by surface id. */
export function previousRows(doc: string): Map<string, PreviousRow> {
  const rows = new Map<string, PreviousRow>()
  const lines = doc.split('\n')
  for (const line of lines) {
    const row = /^\| `([^`]+)` .*?\| [^|]+ \| ([a-z-]+) \| ((?:[^|]*\|){5})/.exec(line)
    if (!row) continue
    const cells = row[3].split('|').slice(0, 5).map((c) => c.trim())
    rows.set(row[1], { status: row[2] as Status, cells, interactions: '' })
  }
  for (let i = 0; i < lines.length; i++) {
    const entry = /^- `([^`]+)`(.*)$/.exec(lines[i])
    const row = entry && rows.get(entry[1])
    if (!entry || !row) continue
    const body = [entry[2]]
    while (lines[i + 1]?.startsWith('  - ')) body.push(lines[++i])
    row.interactions = body.join('\n')
  }
  return rows
}

const pct = (n: number) => `${n.toFixed(1)}%`
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function passed(run?: ClientRun): string {
  if (!run) return 'n/a'
  const total = run.checks.length + run.actions.length
  const ok = run.checks.filter((c) => c.pass).length + run.actions.filter((a) => a.ok).length
  return run.error && total === 0 ? 'crash' : `${ok}/${total}`
}

function mismatch(result?: SurfaceResult): [string, string] {
  const last = result?.diffs.at(-1)
  if (!last) return ['', '']
  const format = (d: typeof last.full) =>
    `${pct(d.exact.percent)} / ${d.perceptual.percent.toFixed(2)}%`
  return [format(last.full), last.roi ? format(last.roi.diff) : '']
}

const unmeasured = (status: Status) =>
  status === 'pending-unit' || status === 'blocked' || status === 'unverified'
const mean = (list: Row[]) =>
  list.length ? list.reduce((sum, r) => sum + STATUS_SCORE[r.status], 0) / list.length : 0

function weighted(byArea: Map<AreaId, Row[]>, keep: (row: Row) => boolean): number {
  let total = 0
  let weight = 0
  for (const [area, list] of byArea) {
    const pool = list.filter(keep)
    if (pool.length === 0) continue
    total += AREA_WEIGHTS[area] * mean(pool)
    weight += AREA_WEIGHTS[area]
  }
  return weight ? (total / weight) * 100 : 0
}

function interactions(row: Row): string {
  const { result, surface } = row
  if (!result?.web) {
    return ` ${surface.pending ? `pending ${surface.pending.unit}: ${surface.pending.reason}` : (surface.blocked ?? 'not run')}`
  }
  const lines: string[] = []
  for (const step of surface.steps) {
    const parts: string[] = []
    const gpuixActions = result.gpuix?.actions.filter((a) => a.step === step.name) ?? []
    for (const [i, action] of result.web.actions.filter((a) => a.step === step.name).entries()) {
      const g = gpuixActions[i]
      const gpuix = g ? `${g.ok ? 'ok' : `FAIL ${g.error}`} via ${g.via}` : 'not run'
      parts.push(
        `${action.action} (web ${action.ok ? 'ok' : `FAIL ${action.error}`}; gpuix ${gpuix})`
      )
    }
    const gpuixChecks = result.gpuix?.checks.filter((c) => c.step === step.name) ?? []
    for (const [i, check] of result.web.checks.filter((c) => c.step === step.name).entries()) {
      const g = gpuixChecks[i]
      parts.push(
        `${check.expect} "${check.text}": web ${check.pass ? 'pass' : 'FAIL'}, gpuix ${g ? (g.pass ? 'pass' : 'FAIL') : 'not run'}`
      )
    }
    lines.push(`  - \`${step.name}\`: ${parts.length ? cell(parts.join('; ')) : 'frame only'}`)
  }
  if (result.web.error) lines.push(`  - web error: ${cell(result.web.error)}`)
  if (result.gpuix?.error) lines.push(`  - gpuix error: ${cell(result.gpuix.error)}`)
  return `\n${lines.join('\n')}`
}

export function renderMatrix(
  results: Record<string, SurfaceResult>,
  previous: ReadonlyMap<string, PreviousRow> = new Map()
): string {
  const rows: Row[] = SURFACES.map((surface) => {
    const result = results[surface.id]
    const review = REVIEWS[surface.id]
    const prior = result ? undefined : previous.get(surface.id)
    return { surface, result, review, previous: prior, status: finalStatus(result, review, prior) }
  })
  const byArea = new Map<AreaId, Row[]>()
  for (const row of rows)
    byArea.set(row.surface.area, [...(byArea.get(row.surface.area) ?? []), row])
  const measured = rows.filter((r) => !unmeasured(r.status))
  const counts = STATUSES.map(
    (status) => `${status} ${rows.filter((r) => r.status === status).length}`
  ).join(', ')

  const out: string[] = [`Surfaces: ${rows.length} (${counts}).`, '']
  out.push(
    '| Score | All surfaces (pending, blocked and unverified count 0) | Measured surfaces only |'
  )
  out.push('| --- | ---: | ---: |')
  out.push(`| Unweighted | ${pct(mean(rows) * 100)} | ${pct(mean(measured) * 100)} |`)
  out.push(
    `| Usage-weighted | ${pct(weighted(byArea, () => true))} | ${pct(weighted(byArea, (r) => !unmeasured(r.status)))} |`
  )
  out.push('', '### By area', '')
  out.push(
    '| Area | Weight | Surfaces | Ported | Partial | Broken | Blocked, pending or unverified | Area score |'
  )
  out.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
  for (const [area, list] of [...byArea].sort((a, b) => AREA_WEIGHTS[b[0]] - AREA_WEIGHTS[a[0]])) {
    const n = (status: Status) => list.filter((r) => r.status === status).length
    out.push(
      `| ${area} | ${AREA_WEIGHTS[area]} | ${list.length} | ${n('ported')} | ${n('partial')} | ${n('broken')} | ${n('blocked') + n('pending-unit') + n('unverified')} | ${pct(mean(list) * 100)} |`
    )
  }

  out.push(
    '',
    '### Ranked gaps',
    '',
    'Rank is the reviewed impact (1 to 3) times the area weight.',
    ''
  )
  out.push('| # | Surface | Status | Root cause class | Proposed unit | Rank | What differs |')
  out.push('| ---: | --- | --- | --- | --- | ---: | --- |')
  const gaps = rows
    .filter((r) => r.review?.cause && r.status !== 'ported')
    .map((row) => ({ row, rank: (row.review?.impact ?? 1) * AREA_WEIGHTS[row.surface.area] }))
    .sort((a, b) => b.rank - a.rank)
  for (const [i, { row, rank }] of gaps.entries()) {
    out.push(
      `| ${i + 1} | \`${row.surface.id}\` | ${row.status} | ${row.review?.cause} | ${row.review?.unit ?? ''} | ${rank} | ${cell(row.review?.differences.join(' ') ?? '')} |`
    )
  }

  out.push('', '### Proposed units', '')
  out.push(
    'Each unit with the surfaces its gaps name. Gain is the usage-weighted score (all surfaces) the matrix would report if every one of those surfaces became ported, everything else unchanged.',
    ''
  )
  out.push('| # | Unit | Root cause class | Surfaces | Summed rank | Gain |')
  out.push('| ---: | --- | --- | ---: | ---: | ---: |')
  const base = weighted(byArea, () => true)
  const units = new Map<string, { cause: string; rows: Row[]; rank: number }>()
  for (const { row, rank } of gaps) {
    const unit = row.review?.unit ?? 'unassigned'
    const entry = units.get(unit) ?? { cause: row.review?.cause ?? '', rows: [], rank: 0 }
    entry.rows.push(row)
    entry.rank += rank
    units.set(unit, entry)
  }
  const gainOf = (fixed: Set<Row>) => {
    const flipped = new Map<AreaId, Row[]>()
    for (const [area, list] of byArea)
      flipped.set(
        area,
        list.map((r) => (fixed.has(r) ? { ...r, status: 'ported' as Status } : r))
      )
    return weighted(flipped, () => true) - base
  }
  const ranked = [...units].map(([unit, entry]) => ({
    unit,
    ...entry,
    gain: gainOf(new Set(entry.rows))
  }))
  ranked.sort((a, b) => b.rank - a.rank)
  for (const [i, u] of ranked.entries()) {
    out.push(
      `| ${i + 1} | ${u.unit} | ${u.cause} | ${u.rows.length} | ${u.rank} | +${u.gain.toFixed(1)} |`
    )
  }
  out.push(
    '',
    `If every listed unit landed and fixed its surfaces, the usage-weighted score would be ${pct(base + gainOf(new Set(gaps.map((g) => g.row))))}.`
  )

  out.push('', '### Surfaces', '')
  out.push(
    'Web and GPUIX columns count passed actions plus checks over the total. Mismatch is exact / perceptual for the last step: the full 1280x800 frame, and the region the surface names (measured in the web client, cropped from both frames).',
    ''
  )
  out.push(
    '| Surface | Area | Status | Auto | Web | GPUIX | Full mismatch | Region mismatch | Differences seen |'
  )
  out.push('| --- | --- | --- | --- | ---: | ---: | ---: | ---: | --- |')
  for (const row of rows) {
    const [full, roi] = mismatch(row.result)
    const measuredCells = row.previous?.cells ?? [row.result?.auto ?? '', passed(row.result?.web), passed(row.result?.gpuix), full, roi]
    out.push(
      `| \`${row.surface.id}\` ${cell(row.surface.title)} | ${row.surface.area} | ${row.status} | ${measuredCells.join(' | ')} | ${cell(row.review?.differences.join(' ') ?? '')} |`
    )
  }

  out.push('', '### Driven interactions and literal results', '')
  for (const row of rows) {
    if (row.previous?.interactions) {
      out.push(`- \`${row.surface.id}\`${row.previous.interactions}`)
      continue
    }
    const first = row.result?.web?.frames[0]
    const frames = first ? ` (frames \`${path.dirname(path.dirname(first))}/\`)` : ''
    out.push(`- \`${row.surface.id}\`${frames}:${interactions(row)}`)
  }
  return out.join('\n')
}

export function writeReport(results: Record<string, SurfaceResult>): void {
  const doc = existsSync(DOC)
    ? readFileSync(DOC, 'utf8')
    : `# GPUIX parity matrix\n\n${BEGIN}\n${END}\n`
  const start = doc.indexOf(BEGIN)
  const end = doc.indexOf(END)
  if (start < 0 || end < start) throw new Error(`${DOC} lost its matrix markers`)
  writeFileSync(
    DOC,
    `${doc.slice(0, start + BEGIN.length)}\n\n${renderMatrix(results, previousRows(doc.slice(start, end)))}\n\n${doc.slice(end)}`
  )
  console.error(`[matrix] wrote ${DOC}`)
}
