/**
 * Generates src/style/generated/tailwind-colors.ts from tailwind.config.ts
 * (colour name -> CSS variable) and the :root block of src/renderer/index.css
 * (first-paint defaults, which also supply tokens applyColorTheme never
 * writes, such as --project-*). Rerun after either file changes:
 *
 *   bun tools/style/gen-color-vars.ts [--check]
 */
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { REPO } from './tailwind-css'

const OUT = join(import.meta.dir, '../../src/style/generated/tailwind-colors.ts')

type ColorTree = { [name: string]: string | ColorTree }

async function loadConfigColors(): Promise<ColorTree> {
  const config = (await import(join(REPO, 'tailwind.config.ts'))).default
  return config.theme.extend.colors as ColorTree
}

/** `oklch(var(--x) / <alpha-value>)` -> `--x`; `var(--x)` -> `var:--x`. */
function flatten(tree: ColorTree, prefix = '', out: Record<string, string> = {}) {
  for (const [key, value] of Object.entries(tree)) {
    const name = key === 'DEFAULT' ? prefix : prefix ? `${prefix}-${key}` : key
    if (typeof value !== 'string') {
      flatten(value, name, out)
      continue
    }
    const oklch = value.match(/^oklch\(var\((--[\w-]+)\) \/ <alpha-value>\)$/)
    const plain = value.match(/^var\((--[\w-]+)\)$/)
    if (oklch) out[name] = oklch[1]
    else if (plain) out[name] = `var:${plain[1]}`
    else throw new Error(`tailwind colour ${name} has an unexpected form: ${value}`)
  }
  return out
}

/** Every `--name: <value>;` in the first `:root {` block of index.css. */
function rootDefaults(): Record<string, string> {
  const css = readFileSync(join(REPO, 'src/renderer/index.css'), 'utf8')
  const start = css.indexOf(':root {')
  const block = css.slice(start, css.indexOf('\n  }\n', start))
  const out: Record<string, string> = {}
  for (const match of block.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+):\s*([^;]+);/g)) {
    out[match[1]] = match[2].replace(/\s+/g, ' ').trim()
  }
  return out
}

/** Format with the repo's Biome so the checked-in file passes `biome ci`. */
function biomeFormat(source: string): string {
  const out = spawnSync(join(REPO, 'node_modules/.bin/biome'), ['format', `--stdin-file-path=${OUT}`], {
    input: source,
    encoding: 'utf8',
    cwd: REPO
  })
  if (out.status !== 0) throw new Error(`biome format failed: ${out.stderr}`)
  return out.stdout
}

export async function generate(): Promise<string> {
  const colors = flatten(await loadConfigColors())
  const defaults = rootDefaults()
  return biomeFormat(`// Generated by tools/style/gen-color-vars.ts from tailwind.config.ts and
// src/renderer/index.css. Do not edit by hand.

/** Tailwind colour name -> CSS variable. \`var:\` marks a raw var() colour. */
export const TAILWIND_COLOR_VARS: Record<string, string> = ${JSON.stringify(colors, null, 2)}

/** index.css \`:root\` first-paint values. applyColorTheme overrides most. */
export const ROOT_CSS_DEFAULTS: Record<string, string> = ${JSON.stringify(defaults, null, 2)}
`)
}

if (import.meta.main) {
  const text = await generate()
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8')
    if (current !== text) {
      console.error(
        'src/style/generated/tailwind-colors.ts is stale; run bun tools/style/gen-color-vars.ts'
      )
      process.exit(1)
    }
    console.log('tailwind-colors.ts is current')
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${OUT}`)
  }
}
