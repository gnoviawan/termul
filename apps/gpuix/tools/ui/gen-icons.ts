/**
 * Generate apps/gpuix/src/icons/index.tsx from src/renderer/components/icons/index.tsx,
 * so the GPUIX icon module exports exactly the names and Hugeicons glyphs the
 * web module does.
 *
 *   bun tools/ui/gen-icons.ts           write the file
 *   bun tools/ui/gen-icons.ts --check   exit 1 if the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const APP_DIR = path.resolve(import.meta.dir, '../..')
export const WEB_ICONS = path.resolve(APP_DIR, '../../src/renderer/components/icons/index.tsx')
export const GPUIX_ICONS = path.join(APP_DIR, 'src/icons/index.tsx')

export function generateIcons(webSource: string): string {
  const imports = webSource.match(/import \{[^}]+\} from '@hugeicons\/core-free-icons'/)
  if (!imports) throw new Error('no @hugeicons/core-free-icons import in the web icon module')
  const exports: string[] = []
  for (const line of webSource.split('\n')) {
    if (/^export const \w+ = hugeIcon\('\w+', \w+\)$/.test(line)) exports.push(line)
    else if (/^export const \w+ = \w+$/.test(line)) exports.push(line)
    else if (/^\/\/ /.test(line) && exports.length > 0) exports.push(line)
  }
  if (!/export const Square = forwardRef/.test(webSource)) {
    throw new Error('the web icon module no longer hand-writes Square; update gen-icons.ts')
  }
  return `// Generated by tools/ui/gen-icons.ts from src/renderer/components/icons/index.tsx. Do not edit.
${imports[0]}
import { hugeIcon, Square } from './termul-icon'

export type { TermulIcon, TermulIconProps } from './termul-icon'
export { Square }

${exports.join('\n')}
`
}

if (import.meta.main) {
  const next = generateIcons(readFileSync(WEB_ICONS, 'utf8'))
  if (process.argv.includes('--check')) {
    const current = readFileSync(GPUIX_ICONS, 'utf8')
    if (current !== next) {
      console.error(
        `${path.relative(APP_DIR, GPUIX_ICONS)} is stale: run bun tools/ui/gen-icons.ts`
      )
      process.exit(1)
    }
    console.log('icons up to date')
  } else {
    writeFileSync(GPUIX_ICONS, next)
    console.log(`wrote ${path.relative(APP_DIR, GPUIX_ICONS)}`)
  }
}
